def extract_section(html, section_id):

    # Remove elements that are normally page navigation or technical content
    for tag in soup.select(
        "header, nav, footer, aside, script, style, "
        "button, form, input"
    ):
        tag.decompose()

    # Remove specific unwanted links or labels
    unwanted_text = {
        "GitLab",
        "Handbook",
        "Light",
        "Dark",
        "Auto",
        "Toggle theme Light Dark Auto"
    }

    for tag in soup.find_all(["a", "span", "div"]):
        text = tag.get_text(" ", strip=True)

        if text in unwanted_text:
            tag.decompose()

    # Find the section where extraction should begin
    heading = soup.find(id=section_id)

    if heading is None:
        return pd.DataFrame()

    rows = []
    section_title = heading.get_text(" ", strip=True)
    subsection_title = None

    # Extract only content after the selected heading
    for element in heading.find_all_next(["h3", "h4", "p", "li"]):

        # Stop when the next main section begins
        if element.name == "h3" and element is not heading:
            break

        text = element.get_text(" ", strip=True)

        if not text:
            continue

        if element.name == "h4":
            subsection_title = text

        elif element.name == "p":
            rows.append({
                "section_title": section_title,
                "subsection_title": subsection_title,
                "content_type": "paragraph",
                "content": text
            })

        elif element.name == "li":
            rows.append({
                "section_title": section_title,
                "subsection_title": subsection_title,
                "content_type": "list_item",
                "content": text
            })

    return pd.DataFrame(rows)


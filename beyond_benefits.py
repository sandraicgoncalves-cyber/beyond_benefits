# extracting the content without navigation and other unrelated content
def extract_content(html):
    # Prefer the main article/content area if the page has one
    content = soup.find("main") or soup.find("article") or soup

    # Remove common navigation and non-content elements
    for tag in content.select(
        "header, nav, footer, aside, script, style, "
        ".navigation, .navbar, .menu, .breadcrumb, "
        ".td-heading-self-link"
    ):
        tag.decompose()

    unwanted_text = {
        "GitLab",
        "Handbook",
        "Toggle theme Light Dark Auto",
        "Light",
        "Dark"
    }

    rows = []
    section_title = None
    subsection_title = None

    # Keep headings, paragraphs, and list items in document order
    for element in content.find_all(["h3", "h4", "p", "li"]):

        text = element.get_text(" ", strip=True)

        # Ignore empty or unwanted content
        if not text or text in unwanted_text:
            continue

        if element.name == "h3":
            section_title = text
            subsection_title = None

        elif element.name == "h4":
            subsection_title = text

        elif element.name == "p":
            rows.append({
                "section_title": section_title,
                "subsection_title": subsection_title,
                "content_type": "paragraph",
                "content": text
            })

        elif element.name == "li":
            rows.append({
                "section_title": section_title,
                "subsection_title": subsection_title,
                "content_type": "list_item",
                "content": text
            })

    return pd.DataFrame(rows)


def extract_page_text(url):

    response = requests.get(
        url,
        headers={"User-Agent": "Mozilla/5.0"},
        timeout=30
    )

    response.raise_for_status()

    soup = BeautifulSoup(response.text, "html.parser")

    # Remove irrelevant page elements
    for element in soup.select(
        "nav, footer, header, script, style, noscript"
    ):
        element.decompose()

    # Extract main content
    content = (
        soup.find("main")
        or soup.find("article")
        or soup.find("body")
    )

    return content.get_text(" ", strip=True).lower()


results = []
diagnostics = []

for company, url in websites.items():

    try:
        page_text = extract_page_text(url)

        total_words = len(page_text.split())

        diagnostics.append({
            "Company": company,
            "Extracted characters": len(page_text),
            "Total words": total_words
        })

        for category, terms in keywords.items():

            category_count = 0

            for term in terms:

                pattern = r"\b" + re.escape(term.lower()) + r"\b"

                category_count += len(
                    re.findall(pattern, page_text)
                )

            results.append({
                "Company": company,
                "Category": category,
                "Keyword Count": category_count,
                "Total Words": total_words,
                "Mentions per 1000 Words": round(
                    category_count / total_words * 1000, 2
                ) if total_words else 0
            })

    except requests.RequestException as error:
        print(f"Error scraping {company}: {error}")


website_analysis = pd.DataFrame(results)


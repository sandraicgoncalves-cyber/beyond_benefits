# Loading the dataset and inspecting
benefits_analysis = pd.read_csv("data/benefits_analysis_clean.csv")
employee_benefits = pd.read_csv("data/employee_benefits_analysis_clean.csv")

"""# H1: Employees who report mental health benefits are also more likely to report available mental health resources"""

# Benefit counts
benefit_counts = benefits_analysis["benefits"].value_counts(dropna=True)

fig = px.pie(
    values=benefit_counts.values,
    names=benefit_counts.index,
    title="Reported Mental Health Benefits",
    hole=0.4,
    color_discrete_sequence=px.colors.qualitative.Set2
)

fig.update_traces(
    textposition="outside",
    textinfo="percent+label",
    rotation=90
)

fig.update_layout(
    template="plotly_white",
    title_x=0.5
)

fig.show()

# Benefits x Workplace resources
h1_table = pd.crosstab(
    benefits_analysis["benefits"],
    benefits_analysis["workplace_resources"],
    normalize="index"
) * 100

# Convert the crosstab index into a regular column
h1_plot = h1_table.reset_index()

# Reshape the table for Plotly
h1_plot = h1_plot.melt(
    id_vars="benefits",
    var_name="workplace_resources",
    value_name="percentage"
)

fig = px.bar(
    h1_plot,
    x="benefits",
    y="percentage",
    color="workplace_resources",
    barmode="stack",
    template="plotly_white",
    title="Mental Health Resources by Benefits Availability",
    labels={
        "benefits": "Benefits",
        "percentage": "Percentage",
        "workplace_resources": "Workplace Resources"
    }
)

fig.update_layout(
    yaxis_title="Percentage (%)",
    xaxis_title="Mental Health Benefits",
    yaxis=dict(range=[0, 100])
)

fig.show()

